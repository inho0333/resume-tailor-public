"""Folding a newer résumé into the database without losing anything.

The rule every test here checks one face of: **the database is a superset, so an
import can only add.** The command this replaces regenerated the file, and the
first test is the exact damage that did.
"""

import os
import sys

import pytest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import resume_merge as rm

ORIGINAL = ("Cut model serving cost 41% by moving inference from per-request GPU calls to a "
            "batched CPU path with quantised weights, after a cost review found 80% of spend "
            "came from traffic that tolerated 200ms.")
REWORDED = ("Cut inference cost 41% by batching GPU calls onto a quantised CPU path, after a "
            "review found 80% of spend tolerated 200ms.")
UNRELATED = ("Built the feature store that eight teams now use, after three incidents traced "
             "to training-serving skew nobody could detect.")


def _db(bullets=None, name="NORTHWIND DATA", header="NORTHWIND DATA, San Francisco, CA"):
    return [{
        "name": name,
        "header_text": header,
        "bullets": bullets if bullets is not None else [{
            "id": "northwindd-b1",
            "text": ORIGINAL,
            "tags": {"org": name, "keywords": ["inference"], "content_type": ["cost"]},
            "context": {"why": "spend review", "how": "quantisation", "impact": "41%"},
        }],
    }]


def _block(bullets, header="NORTHWIND DATA, San Francisco, CA"):
    return [{"header_text": header, "context_lines": [header], "bullets": bullets}]


def _verdicts(plan):
    return [i["verdict"] for s in plan["sections"] for i in s["items"]]


# ── the regression this command exists for ──────────────────────────────────

def test_a_newer_resume_never_renumbers_or_drops_hand_written_work():
    """Pointing `bootstrap` at a newer résumé regenerated the file: `context`
    (which is also the allowed-numbers whitelist), `retired`, and every other
    hand-set field were lost, and ids — generated by position — shifted, so
    `base_resume.yaml` ended up pointing at sentences that had moved.

    Here the same document arrives with a bullet inserted ABOVE the existing
    ones, which is the case that used to shift everything.
    """
    db = _db([
        {"id": "northwindd-b1", "text": ORIGINAL,
         "tags": {"org": "NORTHWIND DATA", "keywords": ["inference"], "content_type": []},
         "context": {"why": "spend review", "how": "quantisation", "impact": "41%"}},
        {"id": "northwindd-b2", "text": UNRELATED,
         "tags": {"org": "NORTHWIND DATA", "keywords": [], "content_type": []},
         "retired": True, "label": "Platform"},
    ])
    plan = rm.classify(_block(["A brand new first bullet about ranking quality.",
                               ORIGINAL, UNRELATED]), db)
    sections, summary = rm.apply_plan(plan, db)

    by_id = {b["id"]: b for s in sections for b in s["bullets"]}
    # every existing id still points at its own sentence
    assert by_id["northwindd-b1"]["text"] == ORIGINAL
    assert by_id["northwindd-b2"]["text"] == UNRELATED
    # and everything hanging off those ids survived
    assert by_id["northwindd-b1"]["context"]["why"] == "spend review"
    assert by_id["northwindd-b2"]["retired"] is True
    assert by_id["northwindd-b2"]["label"] == "Platform"
    # the new sentence was added, numbered past what was in use
    assert summary["added"] == ["northwindd-b3"]
    assert by_id["northwindd-b3"]["text"].startswith("A brand new first bullet")


def test_a_bullet_missing_from_the_new_resume_is_kept():
    """The database holds every bullet you could ever use; a résumé shows a
    subset. Absent from this version of the page is not gone from the career."""
    db = _db()
    plan = rm.classify(_block(["A completely different line of work entirely."]), db)
    assert [d["id"] for d in plan["db_only"]] == ["northwindd-b1"]
    sections, _ = rm.apply_plan(plan, db)
    assert "northwindd-b1" in {b["id"] for s in sections for b in s["bullets"]}


# ── classification ──────────────────────────────────────────────────────────

def test_an_identical_bullet_is_unchanged_even_with_different_whitespace():
    plan = rm.classify(_block(["  ".join(ORIGINAL.split())]), _db())
    assert _verdicts(plan) == [rm.UNCHANGED]
    sections, summary = rm.apply_plan(plan, _db())
    assert summary["added"] == [] and summary["replaced"] == []


def test_a_reworded_bullet_is_matched_and_reports_its_shared_figures():
    plan = rm.classify(_block([REWORDED]), _db())
    [item] = plan["sections"][0]["items"]
    assert item["verdict"] == rm.REWORDED
    assert item["id"] == "northwindd-b1"
    assert item["db_text"] == ORIGINAL
    # the figures it shares are what makes the match legible to a human
    assert "41%" in item["shared"] and "80%" in item["shared"]


def test_an_unrelated_bullet_is_new():
    plan = rm.classify(_block([UNRELATED]), _db())
    assert _verdicts(plan) == [rm.NEW]


def test_two_sections_sharing_a_figure_are_not_merged():
    """Matching is scoped to one section, so two employers that both mention a
    round number are never read as the same experience."""
    db = _db() + [{
        "name": "HELIOS ROBOTICS", "header_text": "HELIOS ROBOTICS, Austin, TX",
        "bullets": [{"id": "heliosrobo-b1",
                     "text": "Raised detection precision 41% across 80 fixtures.",
                     "tags": {"org": "HELIOS ROBOTICS", "keywords": [],
                              "content_type": []}}],
    }]
    plan = rm.classify(_block([REWORDED]), db)
    [item] = plan["sections"][0]["items"]
    assert item["id"] == "northwindd-b1"   # not the Helios bullet


def test_one_document_bullet_cannot_match_two_database_bullets():
    """Two near-identical sentences in a document must not both claim the same
    existing bullet, or the second would be filed as a rewording of something
    already accounted for."""
    db = _db([
        {"id": "northwindd-b1", "text": ORIGINAL,
         "tags": {"org": "NORTHWIND DATA", "keywords": [], "content_type": []}},
    ])
    plan = rm.classify(_block([ORIGINAL, REWORDED]), db)
    verdicts = _verdicts(plan)
    assert verdicts[0] == rm.UNCHANGED
    assert verdicts[1] == rm.NEW          # nothing left for it to be a rewording of


# ── what a human's choice does ──────────────────────────────────────────────

def test_keep_is_the_default_for_a_rewording():
    """The project's standing rule: when in doubt the approved sentence stays."""
    db = _db()
    plan = rm.classify(_block([REWORDED]), db)
    sections, summary = rm.apply_plan(plan, db)          # no choices passed
    by_id = {b["id"]: b for s in sections for b in s["bullets"]}
    assert by_id["northwindd-b1"]["text"] == ORIGINAL
    assert summary == {"replaced": [], "added": [], "headers": [], "sections": []}


def test_replace_swaps_the_text_and_keeps_everything_keyed_to_the_id():
    db = _db()
    plan = rm.classify(_block([REWORDED]), db)
    sections, summary = rm.apply_plan(plan, db, choices={"northwindd-b1": rm.REPLACE})
    bullet = {b["id"]: b for s in sections for b in s["bullets"]}["northwindd-b1"]
    assert bullet["text"] == REWORDED
    assert summary["replaced"] == ["northwindd-b1"]
    for field in ("context", "tags"):
        assert field in bullet, f"{field} was dropped by a text replacement"
    assert bullet["context"]["why"] == "spend review"


def test_keep_both_adds_the_new_wording_as_a_second_bullet():
    db = _db()
    plan = rm.classify(_block([REWORDED]), db)
    sections, summary = rm.apply_plan(plan, db, choices={"northwindd-b1": rm.BOTH})
    texts = {b["id"]: b["text"] for s in sections for b in s["bullets"]}
    assert texts["northwindd-b1"] == ORIGINAL
    assert summary["added"] and texts[summary["added"][0]] == REWORDED


def test_the_source_sections_are_not_mutated():
    db = _db()
    plan = rm.classify(_block([REWORDED, UNRELATED]), db)
    rm.apply_plan(plan, db, choices={"northwindd-b1": rm.REPLACE})
    assert db[0]["bullets"][0]["text"] == ORIGINAL
    assert len(db[0]["bullets"]) == 1


# ── sections and headers ────────────────────────────────────────────────────

def test_a_new_employer_is_added_without_a_question():
    db = _db()
    blocks = _block([ORIGINAL]) + _block(
        ["Shipped the thing that did the other thing, twice."],
        header="KURZ ANALYTICS, Berlin, Germany")
    plan = rm.classify(blocks, db)
    assert plan["counts"]["new_sections"] == 1
    sections, summary = rm.apply_plan(plan, db)
    assert summary["sections"] == ["KURZ ANALYTICS"]
    added = [s for s in sections if s["name"] == "KURZ ANALYTICS"][0]
    assert added["header_text"] == "KURZ ANALYTICS, Berlin, Germany"
    assert len(added["bullets"]) == 1


def test_a_changed_header_line_is_reported_but_not_applied_silently():
    """`resume_writer.find_section_block` matches `header_text` character for
    character and `doctor` fails on a mismatch, so a moved office is worth
    catching — and worth asking about rather than assuming."""
    db = _db()
    plan = rm.classify(_block([ORIGINAL], header="NORTHWIND DATA, Remote"), db)
    section = plan["sections"][0]
    assert section["header_changed"] is True
    assert section["db_header_text"] == "NORTHWIND DATA, San Francisco, CA"

    sections, summary = rm.apply_plan(plan, db)
    assert sections[0]["header_text"] == "NORTHWIND DATA, San Francisco, CA"
    assert summary["headers"] == []

    sections, summary = rm.apply_plan(plan, db, header_updates={"NORTHWIND DATA": True})
    assert sections[0]["header_text"] == "NORTHWIND DATA, Remote"
    assert summary["headers"] == [("NORTHWIND DATA",
                                   "NORTHWIND DATA, San Francisco, CA",
                                   "NORTHWIND DATA, Remote")]


# ── ids ─────────────────────────────────────────────────────────────────────

def test_ids_are_allocated_past_the_highest_in_use_not_by_position():
    taken = {"northwindd-b1", "northwindd-b2", "northwindd-b7"}
    assert rm.next_id("NORTHWIND DATA", taken) == "northwindd-b8"


def test_ids_survive_a_gap_and_never_collide():
    """A deleted middle bullet must not let a later import reuse its id — the id
    may still be referenced from base_resume.yaml or the decision journal."""
    taken = {"northwindd-b1", "northwindd-b3"}
    fresh = rm.next_id("NORTHWIND DATA", taken)
    assert fresh == "northwindd-b4"
    assert fresh not in taken


def test_two_new_bullets_in_one_import_get_different_ids():
    plan = rm.classify(_block([UNRELATED, "A second brand new sentence about latency."]),
                       _db())
    new_ids = [i["new_id"] for s in plan["sections"] for i in s["items"] if i["new_id"]]
    assert len(new_ids) == len(set(new_ids)) == 2


def test_the_merged_database_still_loads():
    """The real contract: `resume_db.load_db` validates required fields and
    global id uniqueness, so a merge that breaks either is caught here."""
    import tempfile

    import yaml

    import resume_db

    db = _db()
    plan = rm.classify(_block([REWORDED, UNRELATED]) + _block(
        ["Something new at a new place."], header="KURZ ANALYTICS, Berlin"), db)
    sections, _ = rm.apply_plan(plan, db, choices={"northwindd-b1": rm.BOTH})
    with tempfile.TemporaryDirectory() as d:
        path = os.path.join(d, "resume_db.yaml")
        with open(path, "w", encoding="utf-8") as f:
            yaml.safe_dump({"sections": sections}, f, allow_unicode=True, sort_keys=False)
        loaded = resume_db.load_db(path)
    assert {s["name"] for s in loaded} == {"NORTHWIND DATA", "KURZ ANALYTICS"}


# ── tagging only what changed ───────────────────────────────────────────────

def test_only_added_bullets_are_sent_for_tagging():
    """Handing the whole database to `tag_and_find_gaps` on every import would
    re-tag work the user may have corrected by hand, and cost a model call
    proportional to the database rather than to what changed."""
    db = _db()
    plan = rm.classify(_block([ORIGINAL, UNRELATED]), db)
    to_tag = rm.new_bullets_for_tagging(plan)
    assert [b["text"] for s in to_tag for b in s["bullets"]] == [UNRELATED]


def test_keep_both_sends_the_new_wording_for_tagging():
    db = _db()
    plan = rm.classify(_block([REWORDED]), db)
    assert rm.new_bullets_for_tagging(plan) == []          # KEEP by default
    to_tag = rm.new_bullets_for_tagging(plan, choices={"northwindd-b1": rm.BOTH})
    assert [b["text"] for s in to_tag for b in s["bullets"]] == [REWORDED]


def test_tags_from_the_model_land_on_the_added_bullet():
    db = _db()
    plan = rm.classify(_block([UNRELATED]), db)
    new_id = plan["sections"][0]["items"][0]["new_id"]
    sections, _ = rm.apply_plan(plan, db, tags_by_id={
        new_id: {"keywords": ["feature store"], "content_type": ["platform"]}})
    bullet = {b["id"]: b for s in sections for b in s["bullets"]}[new_id]
    assert bullet["tags"] == {"org": "NORTHWIND DATA", "keywords": ["feature store"],
                              "content_type": ["platform"]}


def test_an_added_bullet_without_tags_still_has_the_required_shape():
    """`resume_db.load_db` requires id/text/tags on every bullet, so a run where
    the tagging call failed must still produce a loadable file."""
    db = _db()
    plan = rm.classify(_block([UNRELATED]), db)
    sections, _ = rm.apply_plan(plan, db, tags_by_id={})
    bullet = sections[0]["bullets"][-1]
    assert set(bullet) >= {"id", "text", "tags"}
    assert bullet["tags"]["org"] == "NORTHWIND DATA"


@pytest.mark.parametrize("field", rm.PRESERVED_FIELDS)
def test_every_preserved_field_survives_a_replacement(field):
    """One case per field, so adding a field to the schema without adding it to
    PRESERVED_FIELDS shows up as a failing test rather than as silent loss."""
    db = _db()
    db[0]["bullets"][0][field] = "sentinel"
    plan = rm.classify(_block([REWORDED]), db)
    sections, _ = rm.apply_plan(plan, db, choices={"northwindd-b1": rm.REPLACE})
    bullet = {b["id"]: b for s in sections for b in s["bullets"]}["northwindd-b1"]
    assert bullet[field] == "sentinel"
    assert bullet["text"] == REWORDED


# ── the collision between "superset" and doctor's content-loss check ────────

def test_extra_database_sections_are_not_a_doctor_failure(tmp_path, monkeypatch):
    """`doctor` failed the moment a résumé from a different job was imported, and
    the fix it suggested was to delete the material just imported.

    A section the base does not mention renders nothing — which is content loss
    only if the base DOCUMENT has a heading for it. When it does not, the
    database simply holds more than this résumé shows, which is the whole point
    of it being a superset.
    """
    import docx
    import yaml

    import config
    import minimal_tailor
    import run

    doc_path = tmp_path / "resume.docx"
    doc = docx.Document()
    for text, style in [("EXPERIENCE", None), ("KURZ ANALYTICS, Berlin", None),
                        ("Automated the weekly reporting pack.", "List Bullet")]:
        doc.add_paragraph(text, style=style)
    doc.save(doc_path)

    db = tmp_path / "resume_db.yaml"
    db.write_text(yaml.safe_dump({"sections": [
        {"name": "KURZ ANALYTICS", "header_text": "KURZ ANALYTICS, Berlin",
         "bullets": [{"id": "kurzanalyt-b1", "text": "Automated the weekly reporting pack.",
                      "tags": {"org": "KURZ ANALYTICS", "keywords": [], "content_type": []}}]},
        # imported from another résumé; this document has no heading for it
        {"name": "NORTHWIND DATA", "header_text": "NORTHWIND DATA, San Francisco, CA",
         "bullets": [{"id": "northwindd-b1", "text": "Rebuilt the ranking service.",
                      "tags": {"org": "NORTHWIND DATA", "keywords": [], "content_type": []}}]},
    ]}))
    base = tmp_path / "base_resume.yaml"
    base.write_text(yaml.safe_dump({
        "source_docx": str(doc_path),
        "sections": [{"name": "KURZ ANALYTICS", "header_text": "KURZ ANALYTICS, Berlin",
                      "bullets": [{"id": "kurzanalyt-b1",
                                   "text": "Automated the weekly reporting pack."}]}],
    }))

    monkeypatch.setattr(config, "DB_PATH", str(db))
    monkeypatch.setattr(config, "BASE_RESUME_PATH", str(doc_path))
    monkeypatch.setattr(minimal_tailor, "BASE_YAML_PATH", str(base))

    rows = run._check_base_resume(str(base))
    assert not [r for r in rows if r[0] == run._FAIL], rows
    assert any("not on this résumé" in r[1] for r in rows), rows


def test_a_section_the_document_does_have_a_heading_for_still_fails(tmp_path, monkeypatch):
    """The other half. If the document has the heading and the base leaves it
    out, that job renders empty — the content-loss case the rule exists for, and
    it must still fail."""
    import docx
    import yaml

    import config
    import minimal_tailor
    import run

    doc_path = tmp_path / "resume.docx"
    doc = docx.Document()
    for text, style in [("EXPERIENCE", None), ("KURZ ANALYTICS, Berlin", None),
                        ("Automated the weekly reporting pack.", "List Bullet"),
                        ("NORTHWIND DATA, San Francisco, CA", None),
                        ("Rebuilt the ranking service.", "List Bullet")]:
        doc.add_paragraph(text, style=style)
    doc.save(doc_path)

    db = tmp_path / "resume_db.yaml"
    db.write_text(yaml.safe_dump({"sections": [
        {"name": "KURZ ANALYTICS", "header_text": "KURZ ANALYTICS, Berlin",
         "bullets": [{"id": "kurzanalyt-b1", "text": "Automated the weekly reporting pack.",
                      "tags": {"org": "KURZ ANALYTICS", "keywords": [], "content_type": []}}]},
        {"name": "NORTHWIND DATA", "header_text": "NORTHWIND DATA, San Francisco, CA",
         "bullets": [{"id": "northwindd-b1", "text": "Rebuilt the ranking service.",
                      "tags": {"org": "NORTHWIND DATA", "keywords": [], "content_type": []}}]},
    ]}))
    base = tmp_path / "base_resume.yaml"
    base.write_text(yaml.safe_dump({
        "source_docx": str(doc_path),
        "sections": [{"name": "KURZ ANALYTICS", "header_text": "KURZ ANALYTICS, Berlin",
                      "bullets": [{"id": "kurzanalyt-b1",
                                   "text": "Automated the weekly reporting pack."}]}],
    }))

    monkeypatch.setattr(config, "DB_PATH", str(db))
    monkeypatch.setattr(config, "BASE_RESUME_PATH", str(doc_path))
    monkeypatch.setattr(minimal_tailor, "BASE_YAML_PATH", str(base))

    rows = run._check_base_resume(str(base))
    failures = [r for r in rows if r[0] == run._FAIL]
    assert failures, rows
    assert "NORTHWIND DATA" in failures[0][1]
