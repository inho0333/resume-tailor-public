"""Folding a newer résumé into the experience database, without losing anything.

## Why this is not just re-running bootstrap

`bootstrap` writes `resume_db.yaml` from scratch. That is right exactly once.
Pointed at a newer résumé it destroys the work the database exists to hold:

- `context` (why / how / impact), which is **also the allowed-numbers
  whitelist** — so losing it silently shrinks what every future rewrite is
  permitted to say
- `retired: true`, `interview_only`, `superseded_by`, `pinned`, `label`
- any hand-corrected `keywords`

And it renumbers. Ids are generated by position (`<slug>-b<n>`), so inserting
one bullet at the top of a section shifts every id below it. `base_resume.yaml`
is deliberately never overwritten, so after such a run it points at ids whose
sentences have moved, and `doctor` fails on a setup that was correct an hour
earlier.

## The idea that makes a merge safe

**The database is a superset; a résumé is one view of it.** The database holds
every bullet you could ever use; any single résumé shows a subset. So importing
a résumé can only ever *add*. A bullet in the database but absent from the new
document is kept, never removed — it is not gone from your career, it just is
not on this version of the page.

That one rule is the whole difference between a destructive regeneration and an
operation you can run every time you touch your résumé.

## How a parsed bullet is matched to an existing one

No new model call. Two signals this repo already relies on, both from
`minimal_tailor`:

- `_word_overlap` — how much of the original wording a sentence kept. The same
  function that decides whether an edit is an edit or a rewrite.
- `_numbers` + `DUP_NUMBER_OVERLAP` — sharing two or more figures means the same
  work written up twice. That threshold was set by a measured incident, where a
  swap candidate repeated a kept bullet's "4,000 tickets / 18%" and the
  recruiter review raised it as a top finding.

Matching is scoped to one section, so two employers that both mention a round
number are never merged.

Everything here is a pure function over plain data: no file I/O, no prompting,
no model. `run.py` owns the questions and the writing.
"""

import re

from minimal_tailor import DUP_NUMBER_OVERLAP, _numbers, _word_overlap

# How much wording two sentences must share to be "the same bullet, reworded".
#
# Deliberately high. Below it, the safe answer is "a new bullet": a wrongly
# separate bullet costs one duplicate in a file the user reads anyway, while a
# wrongly merged one hides a sentence behind a question about replacing
# something it has nothing to do with.
REWORD_WORD_OVERLAP = 0.6

# Verdicts, in the order a report shows them.
UNCHANGED = "unchanged"
REWORDED = "reworded"
NEW = "new"

# Fields that belong to the user's own work on a bullet and survive any merge.
# Replacing a bullet's text keeps its id, so everything keyed to that id stays
# with it; this tuple exists to say so out loud and to be asserted in tests.
PRESERVED_FIELDS = ("context", "label", "retired", "interview_only",
                    "superseded_by", "pinned", "period")


def _norm(text):
    return " ".join((text or "").split())


def _slug(name):
    """Section name -> id prefix. Same rule bootstrap uses, so ids stay familiar."""
    s = "".join(ch for ch in (name or "").lower() if ch.isalnum())
    return s[:10] or "sec"


def next_id(section_name, taken):
    """A fresh id for `section_name` that is not in `taken`.

    Numbered past the highest `<slug>-b<n>` already used rather than by
    position, because an id is a permanent handle: `base_resume.yaml`,
    `state/decisions.jsonl` and any `tailor --keep <id>` all reference it.
    """
    prefix = _slug(section_name)
    used = set(taken)
    highest = 0
    pattern = re.compile(rf"^{re.escape(prefix)}-b(\d+)$")
    for existing in used:
        match = pattern.match(existing)
        if match:
            highest = max(highest, int(match.group(1)))
    candidate = highest + 1
    while f"{prefix}-b{candidate}" in used:
        candidate += 1
    return f"{prefix}-b{candidate}"


def _match_in_section(text, db_bullets, already_matched):
    """The existing bullet this sentence is a version of, or None.

    Returns (bullet, verdict, shared_figures).
    """
    normalised = _norm(text)
    for bullet in db_bullets:
        if bullet["id"] in already_matched:
            continue
        if _norm(bullet.get("text")) == normalised:
            return bullet, UNCHANGED, []

    best = None
    for bullet in db_bullets:
        if bullet["id"] in already_matched:
            continue
        existing = bullet.get("text") or ""
        overlap = _word_overlap(existing, text)
        shared = sorted(_numbers(text) & _numbers(existing))
        if overlap >= REWORD_WORD_OVERLAP or len(shared) >= DUP_NUMBER_OVERLAP:
            score = (overlap, len(shared))
            if best is None or score > best[0]:
                best = (score, bullet, shared)
    if best:
        return best[1], REWORDED, best[2]
    return None, NEW, []


def classify(blocks, db_sections):
    """Compare a parsed document against the database. Returns a plan.

    blocks: `resume_parser.parse_experience_blocks` output — each
        {"header_text", "context_lines", "bullets": [str]}
    db_sections: `resume_db.load_db` output

    The plan is plain data so `run.py` can print it, ask about it, and apply it
    without this module knowing anything about terminals:

        {
          "sections": [
            {"name", "header_text", "db_header_text", "header_changed",
             "is_new_section",
             "items": [{"verdict", "text", "id"|None, "db_text"|None,
                        "shared"|[], "new_id"|None}]}
          ],
          "db_only": [{"section", "id", "text"}],   # kept, never removed
          "counts": {"unchanged", "reworded", "new", "new_sections", "db_only"},
        }
    """
    by_name = {s["name"]: s for s in db_sections}
    taken = {b["id"] for s in db_sections for b in s["bullets"]}
    plan_sections = []
    matched_ids = set()

    for block in blocks:
        name = section_name_from_header(block["header_text"])
        db_section = by_name.get(name)
        db_bullets = (db_section or {}).get("bullets") or []
        items = []
        for text in block["bullets"]:
            bullet, verdict, shared = _match_in_section(text, db_bullets, matched_ids)
            item = {"verdict": verdict, "text": _norm(text), "shared": shared,
                    "id": None, "db_text": None, "new_id": None}
            if bullet is not None:
                matched_ids.add(bullet["id"])
                item["id"] = bullet["id"]
                item["db_text"] = bullet.get("text")
            if verdict != UNCHANGED:
                # An id is reserved here for EVERY item that could become a new
                # bullet — including a rewording, because the human may choose
                # to keep both. Allocating it lazily at apply time instead meant
                # a "keep both" and a genuinely new bullet in the same import
                # could be handed the same id, which `resume_db.load_db` then
                # rejected as a duplicate.
                #
                # A reserved id that goes unused (a rewording the user keeps)
                # simply leaves a gap in the numbering, which is harmless: ids
                # are opaque handles and `next_id` allocates past the highest.
                item["new_id"] = next_id(name, taken)
                taken.add(item["new_id"])
            items.append(item)

        db_header = (db_section or {}).get("header_text")
        plan_sections.append({
            "name": name,
            "header_text": block["header_text"],
            "db_header_text": db_header,
            # A changed employer line matters out of proportion to how it looks:
            # `resume_writer.find_section_block` matches it character for
            # character, and `doctor` fails outright on a mismatch.
            "header_changed": bool(db_header and db_header != block["header_text"]),
            "is_new_section": db_section is None,
            "items": items,
        })

    db_only = [
        {"section": section["name"], "id": bullet["id"], "text": bullet.get("text")}
        for section in db_sections
        for bullet in section["bullets"]
        if bullet["id"] not in matched_ids
    ]

    counts = {
        "unchanged": sum(1 for s in plan_sections for i in s["items"]
                         if i["verdict"] == UNCHANGED),
        "reworded": sum(1 for s in plan_sections for i in s["items"]
                        if i["verdict"] == REWORDED),
        "new": sum(1 for s in plan_sections for i in s["items"] if i["verdict"] == NEW),
        "new_sections": sum(1 for s in plan_sections if s["is_new_section"]),
        "db_only": len(db_only),
    }
    return {"sections": plan_sections, "db_only": db_only, "counts": counts}


def section_name_from_header(header_text):
    """Same convention as resume_db.yaml and resume_parser."""
    name = (header_text or "").split(",")[0].split("(")[0].strip()
    return name or (header_text or "").strip()


# Choices a human can make about a `reworded` item.
KEEP = "keep"
REPLACE = "replace"
BOTH = "both"


def apply_plan(plan, db_sections, choices=None, header_updates=None, tags_by_id=None):
    """Build the new section list. Returns (sections, summary).

    choices: {bullet id -> KEEP | REPLACE | BOTH}. Anything unlisted is KEEP —
        the default throughout this project is to leave the approved sentence
        alone.
    header_updates: {section name -> True} for header lines to adopt.
    tags_by_id: {new id -> {"keywords", "content_type"}} from
        `bootstrap_engine.tag_and_find_gaps`, for the added bullets only.

    `db_sections` is not mutated; the bullets are copied.
    """
    choices = choices or {}
    header_updates = header_updates or {}
    tags_by_id = tags_by_id or {}

    sections = []
    for section in db_sections:
        sections.append({**section, "bullets": [dict(b) for b in section["bullets"]]})
    by_name = {s["name"]: s for s in sections}
    summary = {"replaced": [], "added": [], "headers": [], "sections": []}

    for planned in plan["sections"]:
        name = planned["name"]
        target = by_name.get(name)
        if target is None:
            target = {"name": name, "header_text": planned["header_text"], "bullets": []}
            sections.append(target)
            by_name[name] = target
            summary["sections"].append(name)
        elif planned["header_changed"] and header_updates.get(name):
            target["header_text"] = planned["header_text"]
            summary["headers"].append((name, planned["db_header_text"],
                                       planned["header_text"]))

        by_id = {b["id"]: b for b in target["bullets"]}
        for item in planned["items"]:
            if item["verdict"] == UNCHANGED:
                continue

            if item["verdict"] == REWORDED:
                choice = choices.get(item["id"], KEEP)
                if choice == KEEP:
                    continue
                if choice == REPLACE:
                    # The id survives, so context/retired/label and everything
                    # else keyed to it stays with the new sentence.
                    by_id[item["id"]]["text"] = item["text"]
                    summary["replaced"].append(item["id"])
                    continue
                # BOTH: the document's wording joins the database as a second
                # angle on the same experience. `minimal_tailor._duplicate_of_kept`
                # already refuses to put two bullets sharing figures on one page,
                # so this cannot produce a résumé that says the same thing twice.

            # Reserved by classify, so two additions in one import cannot collide.
            new_id = item["new_id"] or next_id(
                name, {b["id"] for s in sections for b in s["bullets"]})
            tags = tags_by_id.get(new_id) or {}
            target["bullets"].append({
                "id": new_id,
                "text": item["text"],
                "tags": {
                    "org": name,
                    "keywords": tags.get("keywords") or [],
                    "content_type": tags.get("content_type") or [],
                },
            })
            summary["added"].append(new_id)

    return sections, summary


def new_bullets_for_tagging(plan, choices=None):
    """A sections-shaped structure holding only the bullets about to be added.

    `bootstrap_engine.tag_and_find_gaps` takes sections and tags every bullet in
    them. Handing it the whole database on every import would re-tag work the
    user may have corrected by hand, and spend a model call proportional to the
    database rather than to what actually changed.
    """
    choices = choices or {}
    out = []
    for planned in plan["sections"]:
        bullets = []
        for item in planned["items"]:
            if item["verdict"] == NEW or (
                    item["verdict"] == REWORDED
                    and choices.get(item["id"], KEEP) == BOTH):
                if item["new_id"]:
                    bullets.append({"id": item["new_id"], "text": item["text"]})
        if bullets:
            out.append({"name": planned["name"],
                        "header_text": planned["header_text"],
                        "bullets": bullets})
    return out
